/// `lang_tag` is a BCP-47 tag such as `en-US` or `uk-UA`.
pub fn strings_for(lang_tag: &str) -> &'static Strings {
    let lang = lang_tag.split(['-', '_']).next().unwrap_or("").to_ascii_lowercase();
    match lang.as_str() {
        "uk" => &UK,
        _ => &EN,
    }
}
